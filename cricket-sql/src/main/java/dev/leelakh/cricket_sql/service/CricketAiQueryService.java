
package dev.leelakh.cricket_sql.service;

import dev.leelakh.cricket_sql.conztraints.SqlValidator;
import dev.leelakh.cricket_sql.model.CricketQueryPlan;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Map;

@Service
public class CricketAiQueryService {

    private static final Logger logger =
            LoggerFactory.getLogger(CricketAiQueryService.class);

    private final CricketAiService cricketAiService;
    private final CricketQueryPlanValidator queryPlanValidator;
    private final CricketSqlBuilder cricketSqlBuilder;
    private final SqlValidator sqlValidator;
    private final JdbcTemplate jdbc;

    public CricketAiQueryService(
            CricketAiService cricketAiService,
            CricketQueryPlanValidator queryPlanValidator,
            CricketSqlBuilder cricketSqlBuilder,
            SqlValidator sqlValidator,
            JdbcTemplate jdbc
    ) {
        this.cricketAiService = cricketAiService;
        this.queryPlanValidator = queryPlanValidator;
        this.cricketSqlBuilder = cricketSqlBuilder;
        this.sqlValidator = sqlValidator;
        this.jdbc = jdbc;
    }

    public List<Map<String, Object>> ask(String question) {

        if (question == null || question.isBlank()) {
            throw new IllegalArgumentException(
                    "Question cannot be empty"
            );
        }

        logger.info("Received cricket question: {}", question);

        CricketQueryPlan queryPlan =
                cricketAiService.generateQueryPlan(question);

        logger.info("Query plan generated by AI: {}", queryPlan);

        queryPlanValidator.validate(queryPlan);

        logger.info("Query plan validation successful");

        String generatedSql = cricketSqlBuilder.build(queryPlan);

        logger.info(
                "SQL generated by Java query builder:\n{}",
                generatedSql
        );

        String validatedSql = sqlValidator.validate(generatedSql);

        logger.info("SQL validation successful");

        try {

            logger.info(
                    "Executing SQL with parameters: threshold={}, limit={}",
                    queryPlan.threshold(),
                    queryPlan.limit()
            );

            long startTime = System.currentTimeMillis();

            List<Map<String, Object>> results =
                    jdbc.queryForList(
                            validatedSql,
                            cricketSqlBuilder.parameters(queryPlan).toArray()
                    );

            long executionTime =
                    System.currentTimeMillis() - startTime;

            logger.info(
                    "Query completed successfully. Rows returned: {}, Execution time: {} ms",
                    results.size(),
                    executionTime
            );

            return results;

        } catch (DataAccessException exception) {

            Throwable rootCause = exception.getMostSpecificCause();

            String databaseError =
                    rootCause != null && rootCause.getMessage() != null
                            ? rootCause.getMessage()
                            : exception.getMessage();

            logger.error(
                    "Database execution failed. Error: {}",
                    databaseError,
                    exception
            );

            throw new IllegalStateException(
                    "Unable to execute the generated cricket query: "
                            + databaseError,
                    exception
            );
        }
    }
}
